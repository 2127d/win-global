"""Canonical popup components and reproducible, self-contained QML payloads.

Local copies keep exported plasmoids independent of a system QML install. Never
edit the copies: sync regenerates them; check rejects drift before packaging.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'desktop/components/popups'
TARGETS = [
    ROOT / 'desktop/control-center/SequoiaPopup',
    ROOT / 'desktop/control-center/details/SequoiaPopup',
    ROOT / 'widgets/plasmoids/org.sequoia.startmenu/contents/ui/SequoiaPopup',
    ROOT / 'widgets/plasmoids/org.sequoia.digitalclock/contents/ui/SequoiaPopup',
]


def payload():
    tokens = json.loads((SOURCE / 'tokens.json').read_text())
    qml = '// Generated by tools/popup_components.py from tokens.json.\n'
    qml += '// SPDX-License-Identifier: MIT\npragma Singleton\nimport QtQml\nQtObject {\n'
    qml += ''.join(f'    readonly property real {key}: {value}\n' for key, value in tokens.items())
    qml += '}\n'
    return {**{p.name: p.read_bytes() for p in SOURCE.iterdir()
               if (p.suffix == '.qml' and p.name != 'Tokens.qml') or p.name == 'qmldir'},
            'Tokens.qml': qml.encode()}


def sync(check=False):
    expected = payload()
    failures = []
    for target in [SOURCE, *TARGETS]:
        if target != SOURCE and target.exists():
            for path in target.iterdir():
                if path.is_file() and path.name not in expected:
                    if check:
                        failures.append(str(path.relative_to(ROOT)))
                    else:
                        path.unlink()
        for name, data in expected.items():
            path = target / name
            if path.exists() and path.read_bytes() == data:
                continue
            if check:
                failures.append(str(path.relative_to(ROOT)))
            else:
                target.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
    tokens = json.loads((SOURCE / 'tokens.json').read_text())
    css = '/* Generated by tools/popup_components.py; SPDX-License-Identifier: MIT */\n:root {\n'
    for key, value in tokens.items():
        name = re.sub(r'([A-Z])', lambda m: '-' + m[1].lower(), key)
        unit = '' if key.endswith('Opacity') else 'px'
        css += f'    --sequoia-{name}: {value}{unit};\n'
    css += '}\n'
    path = ROOT / 'themes/union/sequoia-popup-prototype/contents/css/tokens.css'
    if not path.exists() or path.read_text() != css:
        if check:
            failures.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(css)
    if failures:
        raise RuntimeError('Stale popup components; run python3 tools/popup_components.py:\n' + '\n'.join(failures))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    sync(args.check)
    print('Popup components verified' if args.check else 'Popup components synchronized')
