def parse(text):
    """Later explicit entries refine earlier broad synonyms."""
    by_name = {}
    for line in text.splitlines():
        if '=' not in line: continue
        symbol, names = line.split('=', 1)
        for name in names.split(): by_name[name] = symbol.strip()
    grouped = {}
    for name, symbol in by_name.items(): grouped.setdefault(symbol, []).append(name)
    return {symbol: ' '.join(names) for symbol, names in grouped.items()}


def extend(groups):
    for context, text in [('actions', ACTION_MAP), ('devices', DEVICE_MAP), ('status', STATUS_MAP),
                          *[(c, OTHER_MAP) for c in ('categories', 'places', 'emblems', 'preferences', 'mimes', 'apps')]]:
        # Replacing a mapping must remove the old symbol/name association too.
        names = {n:s for s, ns in groups.get(context, {}).items() for n in ns.split()}
        names.update({n:s for s, ns in parse(text).items() for n in ns.split()})
        grouped = {}
        for name,symbol in names.items(): grouped.setdefault(symbol, []).append(name)
        groups[context] = {s:' '.join(ns) for s,ns in grouped.items()}
